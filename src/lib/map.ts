// Статичная картинка карты вместо встроенного интерактивного iframe/JS-виджета —
// по прямой правке клиента («разберись почему у клиента карта не открылась» +
// позже «не буду создавать какие-либо ключи» на предложение подключить
// интерактивную карту): любой встроенный виджет либо требует ключ API, либо
// это iframe за экраном согласия на cookies, который может молча не
// отрисоваться в браузерах со строгой блокировкой сторонних cookies (Safari
// ITP, Firefox strict, Brave, многие корпоративные сети). Обычная картинка не
// зависит ни от cookies, ни от JS, ни от ключа — грузится как любой <img>.
//
// Сама картинка — public/img/map-location.webp, свой файл сайта, а не прямая
// ссылка на static-maps.yandex.ru: бесплатный (без ключа) Static Maps API
// отдаёт максимум 650x450px, а при показе на всю ширину секции (~1150px+)
// это растягивалось почти в 2 раза и выглядело размыто («не нравится карта и
// особенно качество карты»). Файл собран заранее скриптом
// scripts/generate-map-image.py, который сшивает несколько тайлов Яндекса на
// зум глубже в одну чёткую картинку — см. комментарий в самом скрипте.
// Пересобрать: uv run --with pillow --with requests python scripts/generate-map-image.py
// (нужно, если поменяется адрес/координаты в contacts.json).
//
// Без параметра pt (стандартная красная метка Яндекса) в исходных тайлах —
// вместо неё поверх картинки накладывается свой маркер с логотипом (см. места
// использования: contacts.astro, ReviewsWidgets.astro). Картинка всегда
// центрирована на нужную точку, поэтому маркер просто центрируется в контейнере.
export const MAP_IMAGE_PATH = "/img/map-location.webp";

export function mapRouteUrl(lat: number, lon: number): string {
  return `https://yandex.ru/maps/?rtext=~${lat}%2C${lon}`;
}
