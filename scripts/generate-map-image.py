"""Собирает public/img/map-location.webp — статичную картинку карты для
contacts.astro / ReviewsWidgets.astro, без API-ключа Яндекса.

Один прямой снимок Yandex Static Maps API (без ключа, бесплатно, максимум
650x450px) на зум {ZOOM}, сохранённый в WebP БЕЗ потерь (lossless) — выше
уже некуда, дальше упирается в максимум самого источника (650x450px) —
никаких искусственных преобразований поверх того, что реально вернул Яндекс.

Раньше здесь была склейка из нескольких тайлов ради более чёткой картинки на
широкий блок, но она оказалась хрупкой (см. историю в git log этого файла):
на стыках соседних тайлов иногда виден едва заметный излом дороги — Яндекс
рендерит каждый тайл независимо, и даже у математически точных координат
рендер может на пиксель разойтись на стыке. Раньше также была точечная
подрисовка под маркером — вырезать фирменную подпись "Лесная Заимка", которую
Яндекс рисовал прямо под нашим логотипом. На зуме {ZOOM} эта подпись вообще
не появляется (Яндекс подписывает организации только начиная с более
глубокого зума), поэтому и подрисовка тут не нужна — картинка идёт как есть.

Запускать: uv run --with pillow --with requests python scripts/generate-map-image.py
Перезапускать при смене адреса/координат ресторана (см. src/data/contacts.json).
Если понадобится увеличить зум обратно — сначала проверить на свежем снимке,
не появилась ли на этом зуме подпись "Лесная Заимка" под маркером (координаты
маркера — это ровно центр картинки, 325,225 при size=650,450).
"""

import io

import requests
from PIL import Image

LAT, LON = 43.265668, 132.072916  # см. src/data/contacts.json -> lat/lon
ZOOM = 16  # клиент попросил отдалить ещё — на этом зуме Яндекс к тому же
# не подписывает саму "Лесная Заимка" под маркером, подрисовка не нужна
TILE_W, TILE_H = 650, 450
OUT_PATH = "public/img/map-location.webp"


def main() -> None:
    url = f"https://static-maps.yandex.ru/1.x/?ll={LON},{LAT}&z={ZOOM}&l=map&size={TILE_W},{TILE_H}"
    r = requests.get(url, timeout=20)
    r.raise_for_status()
    im = Image.open(io.BytesIO(r.content)).convert("RGB")
    im.save(OUT_PATH, "WEBP", lossless=True, method=6)
    print(f"saved {OUT_PATH}: {im.size[0]}x{im.size[1]}")


if __name__ == "__main__":
    main()
